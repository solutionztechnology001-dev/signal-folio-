import type { Distribution, MetricName, SourceKind, StoreData } from "./types";

export interface DistributionRow {
  distribution: Distribution;
  contentTitle: string;
  totals: Partial<Record<MetricName, number>>; // revenue and cost are per currency below
  revenueByCurrency: Record<string, number>;
  costByCurrency: Record<string, number>;
  sourceKinds: SourceKind[];
  outcomeCount: number;
  conversionRate: number | null; // conversions / clicks, only when both were entered
}

export interface Summary {
  contentCount: number; // non-archived
  archivedCount: number;
  plannedCount: number;
  publishedCount: number;
  failedCount: number;
  outcomeCount: number;
  // Share of published distributions with at least one recorded result.
  // null when nothing is published (never NaN, never a fake 0%).
  outcomeCoverage: number | null;
  totals: { impressions: number; clicks: number; conversions: number };
  revenueByCurrency: Record<string, number>;
  costByCurrency: Record<string, number>;
  sourceKindCounts: Record<SourceKind, number>;
  rows: DistributionRow[];
}

// Every figure here is a sum of numbers the user entered. Nothing is measured,
// estimated, or generated by the app. Demo records are excluded unless asked.
export function summarize(data: StoreData, options: { includeDemo?: boolean } = {}): Summary {
  const includeDemo = options.includeDemo === true;
  const content = data.content.filter((c) => includeDemo || !c.isDemo);
  const contentIds = new Set(content.map((c) => c.id));
  const distributions = data.distributions.filter((d) => contentIds.has(d.contentId) && (includeDemo || !d.isDemo));
  const distIds = new Set(distributions.map((d) => d.id));
  const outcomes = data.outcomes.filter((o) => distIds.has(o.distributionId) && (includeDemo || !o.isDemo));

  const summary: Summary = {
    contentCount: content.filter((c) => c.status !== "archived").length,
    archivedCount: content.filter((c) => c.status === "archived").length,
    plannedCount: distributions.filter((d) => d.status === "planned").length,
    publishedCount: distributions.filter((d) => d.status === "published").length,
    failedCount: distributions.filter((d) => d.status === "failed").length,
    outcomeCount: outcomes.length,
    outcomeCoverage: null,
    totals: { impressions: 0, clicks: 0, conversions: 0 },
    revenueByCurrency: {},
    costByCurrency: {},
    sourceKindCounts: { measured: 0, "user-entered": 0, estimated: 0 },
    rows: [],
  };

  const titleById = new Map(content.map((c) => [c.id, c.title]));
  const published = distributions.filter((d) => d.status === "published");

  for (const d of published) {
    const mine = outcomes.filter((o) => o.distributionId === d.id);
    const row: DistributionRow = {
      distribution: d,
      contentTitle: titleById.get(d.contentId) ?? "(missing content)",
      totals: {},
      revenueByCurrency: {},
      costByCurrency: {},
      sourceKinds: [],
      outcomeCount: mine.length,
      conversionRate: null,
    };
    for (const o of mine) {
      if (!row.sourceKinds.includes(o.sourceKind)) row.sourceKinds.push(o.sourceKind);
      summary.sourceKindCounts[o.sourceKind] += 1;
      if (o.metric === "revenue") {
        row.revenueByCurrency[o.currency] = (row.revenueByCurrency[o.currency] ?? 0) + o.value;
        summary.revenueByCurrency[o.currency] = (summary.revenueByCurrency[o.currency] ?? 0) + o.value;
      } else if (o.metric === "cost") {
        row.costByCurrency[o.currency] = (row.costByCurrency[o.currency] ?? 0) + o.value;
        summary.costByCurrency[o.currency] = (summary.costByCurrency[o.currency] ?? 0) + o.value;
      } else {
        row.totals[o.metric] = (row.totals[o.metric] ?? 0) + o.value;
        summary.totals[o.metric] += o.value;
      }
    }
    const clicks = row.totals.clicks;
    const conversions = row.totals.conversions;
    if (clicks !== undefined && conversions !== undefined && clicks > 0) {
      row.conversionRate = conversions / clicks;
    }
    summary.rows.push(row);
  }

  if (published.length > 0) {
    const withOutcome = summary.rows.filter((r) => r.outcomeCount > 0).length;
    summary.outcomeCoverage = withOutcome / published.length;
  }
  return summary;
}
